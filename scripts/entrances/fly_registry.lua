-- Curated overrides for any region whose auto-derived label reads badly; wins over the deriver.
FLY_REGION_NAME_OVERRIDES = {}

local FLY_NAME_SMALL = { ["of"] = true, ["and"] = true, ["the"] = true }
local FLY_NAME_UPPER = { ne = true, nw = true, se = true, sw = true }

--- Title-cases an underscore-separated chunk (small words stay lowercase mid-string,
--- compass abbreviations stay upper).
---@param s string
---@return string
local function flyTitleWords(s)
    local out = {}
    for word in string.gmatch(s, "[^_]+") do
        local lw = string.lower(word)
        if FLY_NAME_UPPER[lw] then
            out[#out + 1] = string.upper(word)
        elseif FLY_NAME_SMALL[lw] and #out > 0 then
            out[#out + 1] = lw
        else
            out[#out + 1] = lw:sub(1, 1):upper() .. lw:sub(2)
        end
    end
    return table.concat(out, " ")
end

