---@return string
function FlyRegionPrettyName(region)
    if not region then return "????" end
    local override = FLY_REGION_NAME_OVERRIDES[region]
    if override then return override end
    local body = region:gsub("^REGION_", "")
    local base, sub = body:match("^([^:]+):(.+)$")
    if not base then
        return flyTitleWords(body)
    end
    return flyTitleWords(base) .. " (" .. flyTitleWords(sub:gsub(":", "_")) .. ")"
end

